"""Writes the built-in city list from Natural Earth's populated places GeoJSON.

Usage: python -I scripts/cities.py ne_10m_populated_places_simple.geojson Sources/Mononi/Cities.swift
"""

import json
import sys

source, destination = sys.argv[1], sys.argv[2]
with open(source, encoding="utf-8") as file:
    features = json.load(file)["features"]

rows = []
for feature in features:
    place = feature["properties"]
    longitude, latitude = feature["geometry"]["coordinates"]
    population = max(place["pop_max"] or 0, 0)
    code = place["iso_a2"] if place["iso_a2"] != "-99" else ""
    fields = [place["name"], place["adm1name"] or "", place["adm0name"], code, f"{latitude:.4f}", f"{longitude:.4f}"]
    if any("|" in field or "\n" in field for field in fields):
        sys.exit(f"field contains the separator: {fields}")
    rows.append((-population, place["name"], "|".join(fields)))

table = "\n".join(row for *_, row in sorted(rows))

with open(destination, "w", encoding="utf-8") as file:
    file.write(f'''// Generated by scripts/cities.py from Natural Earth's populated places v5.1.2
// (public domain, https://www.naturalearthdata.com). Run `just cities` to regenerate.

extension City {{
    /// One city per line, most populous first: name|region|country|country code|latitude|longitude.
    static let table = #"""
{table}
"""#
}}
''')
print(f"wrote {len(rows)} cities to {destination}")
